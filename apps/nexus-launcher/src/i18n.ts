function detectLocale(): Locale {
  try {
    const stored = window.localStorage.getItem("nexus.launcher.locale");
    if (stored === "en" || stored === "zh") return stored;
  } catch {
    // A restricted webview can disable storage. Browser language is still safe.
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function interpolate(value: string, params?: TranslationParams): string {
  if (!params) return value;
  return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) => (
    params[key] === undefined ? match : String(params[key])
  ));
}

function translate(locale: Locale, key: string, params?: TranslationParams): string {
  const value = locale === "zh" ? chinese[key] ?? english[key] ?? key : english[key] ?? key;
  return interpolate(value, params);
}

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translator;
};

const I18nContext = createContext<I18nContextValue>({
  locale: "en",
  setLocale: () => undefined,
  t: (key, params) => translate("en", key, params),
});

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocale] = useState<Locale>(() => initialLocale ?? detectLocale());
  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    document.title = translate(locale, "Nexus Launcher");
  }, [locale]);
  useEffect(() => {
    try {
      window.localStorage.setItem("nexus.launcher.locale", locale);
    } catch {
      // The current choice still applies when persistence is unavailable.
    }
  }, [locale]);
  const value = useMemo<I18nContextValue>(
    () => ({ locale, setLocale, t: (key, params) => translate(locale, key, params) }),
    [locale],
  );
  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function translateForTest(locale: Locale, key: string, params?: TranslationParams): string {
  return translate(locale, key, params);
}

export function translationKeysForTest(locale: Locale): string[] {
  return Object.keys(locale === "zh" ? chinese : english).sort();
}
